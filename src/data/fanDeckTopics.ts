// Recent history to avoid immediate repeats
const recentIds = new Set<string>();

/**
 * Returns a random topic with balanced variety across all lengths:
 * - One-word concepts (with profound glosses)
 * - Short editorial phrases (2-5 words)
 * - Medium inquiry & debate questions (6-15 words)
 * - Long scenarios / thought experiments (16-45 words)
 * - Curated classic core library topics
 */
export function getRandomTopic(excludeId?: string): TopicEntry {
  // Balanced format selection so user experiences the complete range
  const roll = Math.random();
  let candidatePool: TopicEntry[];

  if (roll < 0.18) {
    // 18% chance: One-word topic
    candidatePool = oneWordPool;
  } else if (roll < 0.40) {
    // 22% chance: Short phrase topic
    candidatePool = shortPool;
  } else if (roll < 0.70) {
    // 30% chance: Medium inquiry & debate
    candidatePool = medPool;
  } else if (roll < 0.85) {
    // 15% chance: Long thought experiment
    candidatePool = longPool;
  } else {
    // 15% chance: Curated classic topic
    candidatePool = curatedPool;
  }

  // Filter recently seen
  const fresh = candidatePool.filter(
    (t) => t.id !== excludeId && !recentIds.has(t.id)
  );
  const pool = fresh.length > 0 ? fresh : candidatePool;
  const pick = pool[Math.floor(Math.random() * pool.length)] || ALL_TOPICS[0];

  recentIds.add(pick.id);
  if (recentIds.size > 80) {
    const first = recentIds.values().next().value;
    if (first) recentIds.delete(first);
  }

  return pick;
}

export function getTopicById(id: string): TopicEntry | undefined {
  return ALL_TOPICS.find((t) => t.id === id);
}

